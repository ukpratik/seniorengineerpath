// Converts the site's Lucide icons (public/icons.svg) into Android vector drawables for the app.
// Run after adding a name to ICONS: node scripts/export-app-icons.mjs. The output is committed.
import { readFileSync, writeFileSync } from 'node:fs';

const ICONS = ['home', 'map', 'search', 'check-circle', 'arrow-left', 'chev-right', 'info', 'sun', 'moon', 'monitor', 'book', 'route'];
const OUT = 'android/app/src/main/res/drawable';

const svg = readFileSync('public/icons.svg', 'utf8');
const attrs = (s) => Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const n = (v, d = 0) => (v === undefined ? d : Number(v));

// Every shape becomes path data, since a vector drawable only draws <path>.
function toPath(tag, a) {
  if (tag === 'path') return a.d;
  if (tag === 'circle') {
    const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)];
    return `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0`;
  }
  if (tag === 'rect') {
    const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)];
    const r = Math.min(n(a.rx, n(a.ry)), w / 2, h / 2);
    if (!r) return `M${x},${y}h${w}v${h}h${-w}z`;
    return `M${x + r},${y}h${w - 2 * r}a${r},${r} 0 0 1 ${r},${r}v${h - 2 * r}a${r},${r} 0 0 1 ${-r},${r}h${-(w - 2 * r)}a${r},${r} 0 0 1 ${-r},${-r}v${-(h - 2 * r)}a${r},${r} 0 0 1 ${r},${-r}z`;
  }
  throw new Error(`unsupported <${tag}>`);
}

for (const name of ICONS) {
  const m = new RegExp(`<symbol id="i-${name}" viewBox="0 0 24 24">([\\s\\S]*?)</symbol>`).exec(svg);
  if (!m) throw new Error(`icon ${name} not in public/icons.svg`);
  const paths = [...m[1].matchAll(/<(\w+)([^>]*)\/>/g)].map(([, tag, rest]) => toPath(tag, attrs(rest)));
  const body = paths
    .map((d) => `    <path\n        android:pathData="${d}"\n        android:strokeColor="#FF000000"\n        android:strokeWidth="2"\n        android:strokeLineCap="round"\n        android:strokeLineJoin="round" />`)
    .join('\n');
  const xml = `<?xml version="1.0" encoding="utf-8"?>\n<!-- Lucide "${name}" (ISC), generated by scripts/export-app-icons.mjs. Tinted by the Icon composable. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24">\n${body}\n</vector>\n`;
  writeFileSync(`${OUT}/ic_${name.replace(/-/g, '_')}.xml`, xml);
}
console.log(`${ICONS.length} icons → ${OUT}`);
